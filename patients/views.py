"""
patients/views.py — Patient API Views

Implements full CRUD (Create, Read, Update, Delete) for patient records
using DRF's ModelViewSet.

Security model:
- All endpoints require JWT authentication (from settings.py default).
- Data isolation: Users can only access patients they created.
  This is enforced at the queryset level, not just in permissions,
  so even direct URL access (/api/patients/999/) won't expose
  another user's data — it returns 404 instead.

Why ModelViewSet?
- A single class provides all five actions: list, create, retrieve, update, destroy.
- Pairs with DRF's Router to auto-generate URL patterns.
- Keeps the codebase DRY — no need for separate views per action.
"""

from rest_framework import viewsets, status
from rest_framework.response import Response
from rest_framework.permissions import IsAuthenticated

from .models import Patient
from .serializers import PatientSerializer


class PatientViewSet(viewsets.ModelViewSet):
    """
    ViewSet for Patient CRUD operations.

    Endpoints (auto-generated by DRF Router):
        GET    /api/patients/        → list()     — All patients for this user
        POST   /api/patients/        → create()   — Add a new patient
        GET    /api/patients/<id>/   → retrieve() — Get one patient's details
        PUT    /api/patients/<id>/   → update()   — Update all fields of a patient
        PATCH  /api/patients/<id>/   → partial_update() — Update some fields
        DELETE /api/patients/<id>/   → destroy()  — Delete a patient record

    Access control:
        - Authentication: Required (JWT token in Authorization header).
        - Data isolation: get_queryset() filters to current user's patients only.
    """

    serializer_class = PatientSerializer

    # IsAuthenticated: Requires a valid JWT token in the request.
    # Without this, unauthenticated requests would reach our views.
    permission_classes = (IsAuthenticated,)

    def get_queryset(self):
        """
        Return only patients created by the currently authenticated user.

        Why override get_queryset() instead of setting queryset = Patient.objects.all()?
        - Patient.objects.all() would return ALL patients in the database,
          exposing other users' data.
        - Filtering by request.user ensures complete data isolation between users.
        - This also means GET /api/patients/<id>/ returns 404 (not 403) if
          the patient belongs to another user — no information leakage about
          whether that ID exists.
        """
        return Patient.objects.filter(created_by=self.request.user)

    def perform_create(self, serializer):
        """
        Automatically set 'created_by' to the authenticated user on creation.

        Why override perform_create()?
        - The 'created_by' field is read-only in the serializer (users shouldn't
          set it themselves — that would allow impersonation).
        - perform_create() is called by ModelViewSet.create() after validation
          passes, right before saving to the database.
        - serializer.save(created_by=...) injects the value that the serializer
          won't accept from user input.
        """
        serializer.save(created_by=self.request.user)

    def create(self, request, *args, **kwargs):
        """
        Override create() to return a structured success response.

        Default ModelViewSet.create() returns just the serialized object.
        We wrap it with a success message for consistent API responses.
        """
        serializer = self.get_serializer(data=request.data)
        serializer.is_valid(raise_exception=True)
        self.perform_create(serializer)

        return Response({
            'success': True,
            'message': 'Patient created successfully.',
            'data': serializer.data
        }, status=status.HTTP_201_CREATED)

    def update(self, request, *args, **kwargs):
        """
        Override update() to return a structured success response.
        Supports both PUT (full update) and PATCH (partial update).
        """
        partial = kwargs.pop('partial', False)
        instance = self.get_object()
        serializer = self.get_serializer(instance, data=request.data, partial=partial)
        serializer.is_valid(raise_exception=True)
        self.perform_update(serializer)

        return Response({
            'success': True,
            'message': 'Patient updated successfully.',
            'data': serializer.data
        }, status=status.HTTP_200_OK)

    def destroy(self, request, *args, **kwargs):
        """
        Override destroy() to return a confirmation message instead of
        an empty 204 response, which is more informative for API consumers.
        """
        instance = self.get_object()
        self.perform_destroy(instance)

        return Response({
            'success': True,
            'message': 'Patient deleted successfully.'
        }, status=status.HTTP_200_OK)
